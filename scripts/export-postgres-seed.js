import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { DatabaseSync } from "node:sqlite";
import { config, rootDir } from "../src/config.js";

const outputPath = resolve(rootDir, process.argv[2] || "data/postgres-seed.sql");

const tables = [
  "organizations",
  "users",
  "companies",
  "accounting_periods",
  "auxiliary_accounts",
  "custom_accounts",
  "journals",
  "journal_entries",
  "journal_lines",
  "classification_corrections",
  "bank_import_batches",
  "subscription_batches",
  "lettering_groups",
  "audit_events",
  "jobs",
  "stored_files"
];

const jsonColumns = new Set([
  "entry_ids_json",
  "line_refs_json",
  "details_json",
  "payload_json",
  "result_json"
]);

const db = new DatabaseSync(config.sqlitePath);
ensureOrganizationColumns(db);
const statements = [
  "-- Generated by scripts/export-postgres-seed.js",
  "-- Apply db/postgres/schema.sql first, then run this file with psql.",
  "BEGIN;",
  `TRUNCATE ${tables.map(quoteIdentifier).join(", ")} RESTART IDENTITY CASCADE;`
];

for (const table of tables) {
  if (!tableExists(table)) continue;
  const columns = db.prepare(`PRAGMA table_info(${quoteIdentifier(table)})`).all().map((column) => column.name);
  const rows = db.prepare(`SELECT * FROM ${quoteIdentifier(table)}`).all();
  if (rows.length === 0) continue;

  statements.push("");
  statements.push(`-- ${table}`);
  statements.push(`INSERT INTO ${quoteIdentifier(table)} (${columns.map(quoteIdentifier).join(", ")}) VALUES`);
  statements.push(rows.map((row, index) => {
    const suffix = index === rows.length - 1 ? ";" : ",";
    return `  (${columns.map((column) => sqlValue(row[column], column)).join(", ")})${suffix}`;
  }).join("\n"));
}

statements.push("COMMIT;");

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, `${statements.join("\n")}\n`, "utf8");
console.log(`Export PostgreSQL genere: ${outputPath}`);

function tableExists(table) {
  return Boolean(db.prepare(`
    SELECT name
    FROM sqlite_master
    WHERE type = 'table' AND name = ?
  `).get(table));
}

function ensureOrganizationColumns(database) {
  const organizationTables = tables.filter((table) => !["organizations", "users", "journal_lines"].includes(table));
  for (const table of organizationTables) {
    if (!tableExists(table)) continue;
    const hasColumn = database.prepare(`PRAGMA table_info(${quoteIdentifier(table)})`).all()
      .some((column) => column.name === "organization_id");
    if (!hasColumn) database.exec(`ALTER TABLE ${quoteIdentifier(table)} ADD COLUMN organization_id TEXT NOT NULL DEFAULT 'demo-company'`);
    database.prepare(`UPDATE ${quoteIdentifier(table)} SET organization_id = ? WHERE organization_id IS NULL OR organization_id = ''`).run("demo-company");
  }
}

function quoteIdentifier(identifier) {
  return `"${String(identifier).replaceAll('"', '""')}"`;
}

function sqlValue(value, column) {
  if (value === null || value === undefined) return "NULL";
  if (typeof value === "number") return Number.isFinite(value) ? String(value) : "NULL";

  const escaped = String(value).replaceAll("'", "''");
  if (jsonColumns.has(column)) return `'${escaped}'::jsonb`;
  return `'${escaped}'`;
}
